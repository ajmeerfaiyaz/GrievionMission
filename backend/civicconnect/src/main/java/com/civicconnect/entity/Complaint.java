package com.civicconnect.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.time.LocalDateTime;

/**
 * Complaint Entity
 * Maps to the 'complaints' table in MySQL for managing citizen grievances,
 * AI predictions, department assignment, and proof attachments.
 */
@Entity
@Table(name = "complaints")
public class Complaint {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(nullable = false)
    private String title;

    @Column(nullable = false, columnDefinition = "TEXT")
    private String description;

    @Column(nullable = false)
    private String category;

    @Column(nullable = false)
    private String location;

    @Column(nullable = false)
    private String priority = "Medium";

    @Column(nullable = false)
    private String status = "PENDING"; // PENDING, IN_PROGRESS, RESOLVED, REJECTED

    @Column(nullable = false)
    private Long createdBy;

    @Column
    private String createdByName;

    @Column(nullable = false)
    private Integer supportCount = 0;

    @Column
    private String department; // Automatically routed or admin assigned

    @Column(columnDefinition = "TEXT")
    private String imageUrl; // URL or path to uploaded photo evidence

    @Column(columnDefinition = "TEXT")
    private String videoUrl; // URL or path to uploaded video evidence

    @Column(columnDefinition = "TEXT")
    private String aiSummary; // Extractive NLP summary generated by AI

    @Column
    private Long isDuplicateOf; // ID of similar complaint if duplicate detected

    @Column(columnDefinition = "TEXT")
    private String adminNotes; // Notes from department officer / admin

    @Column
    private LocalDateTime createdAt = LocalDateTime.now();

    @Column
    private LocalDateTime updatedAt;

    // Default no-argument constructor (required by JPA)
    public Complaint() {
        this.status = "PENDING";
        this.priority = "Medium";
        this.supportCount = 0;
        this.createdAt = LocalDateTime.now();
    }

    // Constructor suitable for creating a new complaint
    public Complaint(String title, String description, String category, String location,
                     String priority, Long createdBy, String createdByName) {
        this.title = title;
        this.description = description;
        this.category = category;
        this.location = location;
        this.priority = (priority != null && !priority.isBlank()) ? priority : "Medium";
        this.status = "PENDING";
        this.createdBy = createdBy;
        this.createdByName = createdByName;
        this.supportCount = 0;
        this.createdAt = LocalDateTime.now();
    }

    // Getters and Setters
    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public String getCategory() {
        return category;
    }

    public void setCategory(String category) {
        this.category = category;
    }

    public String getLocation() {
        return location;
    }

    public void setLocation(String location) {
        this.location = location;
    }

    public String getPriority() {
        return priority;
    }

    public void setPriority(String priority) {
        this.priority = priority;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
        this.updatedAt = LocalDateTime.now();
    }

    public Long getCreatedBy() {
        return createdBy;
    }

    public void setCreatedBy(Long createdBy) {
        this.createdBy = createdBy;
    }

    public String getCreatedByName() {
        return createdByName;
    }

    public void setCreatedByName(String createdByName) {
        this.createdByName = createdByName;
    }

    public Integer getSupportCount() {
        return supportCount;
    }

    public void setSupportCount(Integer supportCount) {
        this.supportCount = supportCount;
    }

    public String getDepartment() {
        return department;
    }

    public void setDepartment(String department) {
        this.department = department;
    }

    public String getImageUrl() {
        return imageUrl;
    }

    public void setImageUrl(String imageUrl) {
        this.imageUrl = imageUrl;
    }

    public String getVideoUrl() {
        return videoUrl;
    }

    public void setVideoUrl(String videoUrl) {
        this.videoUrl = videoUrl;
    }

    public String getAiSummary() {
        return aiSummary;
    }

    public void setAiSummary(String aiSummary) {
        this.aiSummary = aiSummary;
    }

    public Long getIsDuplicateOf() {
        return isDuplicateOf;
    }

    public void setIsDuplicateOf(Long isDuplicateOf) {
        this.isDuplicateOf = isDuplicateOf;
    }

    public String getAdminNotes() {
        return adminNotes;
    }

    public void setAdminNotes(String adminNotes) {
        this.adminNotes = adminNotes;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(LocalDateTime createdAt) {
        this.createdAt = createdAt;
    }

    public LocalDateTime getUpdatedAt() {
        return updatedAt;
    }

    public void setUpdatedAt(LocalDateTime updatedAt) {
        this.updatedAt = updatedAt;
    }
}
